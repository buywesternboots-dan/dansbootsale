-- Public descriptions. Group price, SKU, and cost lines are removed even if
-- someone pasted them into the description.
create or replace function public.scrub_public_text(src text)
returns text
language sql
immutable
as $$
  select nullif(btrim(coalesce((
    select string_agg(line, E'\n')
    from unnest(string_to_array(coalesce(src, ''), E'\n')) as line
    where line !~* 'group[[:space:]]*price'
      and line !~* '^[[:space:]]*(sku|cost|cogs|wholesale|internal|profit)([[:space:]]|:|$)'
      and line !~* '(cost of goods|sold price|shipping cost|other costs|unit[[:space:]]*cost)'
  ), '')), '');
$$;

