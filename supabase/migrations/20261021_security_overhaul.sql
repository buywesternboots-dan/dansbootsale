alter table public.products add column if not exists updated_at timestamptz default now();
alter table public.products add column if not exists sold_at timestamptz;

create or replace function public.public_catalog()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', p.id,
      'gender', p.gender,
      'brand', p.brand,
      'title', p.title,
      'size', p.size,
      'width', p.width,
      'no_width', p.no_width,
      'material', p.material,
      'price', p.price,
      'photos', p.photos,
      'women_size', p.women_size,
      'women_width', p.women_width,
      'status', p.status,
      'description', public.scrub_public_text(p.notes),
      'condition', p.condition,
      'updated_at', p.updated_at,
      'created_at', p.created_at,
      'sold_at', p.sold_at
    ) order by p.id)
    from public.products p
    where p.status in ('published', 'sold')
      and p.price is not null
      and p.price > 0
  ), '[]'::jsonb);
$$;

revoke all on function public.public_catalog() from public;
grant execute on function public.public_catalog() to anon, authenticated;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
drop policy if exists "admin reads own profile" on public.profiles;
create policy "admin reads own profile"
  on public.profiles for select to authenticated
  using (user_id = auth.uid());

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- Existing accounts become admins. If this inserts zero rows, create the
-- Supabase user first, then run the insert again (it is also in APPLY.md).
insert into public.profiles (user_id, role)
select id, 'admin' from auth.users
on conflict (user_id) do nothing;

