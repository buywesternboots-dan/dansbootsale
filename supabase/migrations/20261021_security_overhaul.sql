-- Replace wide-open policies. Service role bypasses RLS and is used only by
-- the staff and wholesale server functions.
do $$
declare r record;
begin
  for r in select policyname from pg_policies where schemaname = 'public' and tablename = 'products' loop
    execute format('drop policy if exists %I on public.products', r.policyname);
  end loop;
  for r in select policyname from pg_policies where schemaname = 'public' and tablename = 'orders' loop
    execute format('drop policy if exists %I on public.orders', r.policyname);
  end loop;
  for r in select policyname from pg_policies where schemaname = 'public' and tablename = 'import_log' loop
    execute format('drop policy if exists %I on public.import_log', r.policyname);
  end loop;
end $$;

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.import_log enable row level security;

create policy "admin all products"
  on public.products for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "admin all orders"
  on public.orders for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "admin all import log"
  on public.import_log for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

revoke all on public.products from anon, public;
revoke all on public.orders from anon, public;
revoke all on public.import_log from anon, public;
grant select, insert, update, delete on public.products to authenticated;
grant select, insert, update, delete on public.orders to authenticated;
grant select, insert, update, delete on public.import_log to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Stop anonymous writes to the photo bucket. Public reads of that bucket stay.
do $$
declare r record;
begin
  for r in
    select policyname
    from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and cmd in ('INSERT', 'UPDATE', 'DELETE', 'ALL')
      and (roles::text ilike '%anon%' or roles::text ilike '%public%')
  loop
    execute format('drop policy if exists %I on storage.objects', r.policyname);
  end loop;
end $$;

drop policy if exists "public read wholesale photos" on storage.objects;
create policy "public read wholesale photos"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'wholesale-photos');

create or replace function public.touch_product_status()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'sold' and (tg_op = 'INSERT' or old.status is distinct from 'sold') then
    new.sold_at = coalesce(new.sold_at, now());
  end if;
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists products_touch_status on public.products;
create trigger products_touch_status
  before insert or update on public.products
  for each row execute function public.touch_product_status();

